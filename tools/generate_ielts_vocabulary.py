#!/usr/bin/env python3
"""Build the deterministic offline IELTS vocabulary asset from ECDICT's CSV."""

from __future__ import annotations

import csv
import gzip
import hashlib
import io
import os
from pathlib import Path
import re
import sys


EXPECTED_TAGGED_WORDS = 5_040


def clean(value: str, *, preserve_breaks: bool = False) -> str:
    value = value.replace("\t", " ").replace("\r", "\n")
    pieces = [re.sub(r"\s+", " ", piece).strip() for piece in value.split("\n")]
    pieces = [piece for piece in pieces if piece]
    return ("；" if preserve_breaks else " ").join(pieces)


def level_for(row: dict[str, str]) -> str:
    try:
        rank = int(row.get("frq") or row.get("bnc") or 99_999)
    except ValueError:
        rank = 99_999
    if rank <= 1_500:
        return "A2"
    if rank <= 4_000:
        return "B1"
    if rank <= 8_000:
        return "B2"
    if rank <= 15_000:
        return "C1"
    return "C2"


def main() -> int:
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_ielts_vocabulary.py ECDICT.csv output.tsv.bin")
    source = Path(sys.argv[1]).resolve()
    destination = Path(sys.argv[2]).resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(destination.suffix + ".tmp")
    seen: set[str] = set()
    count = 0

    with source.open("r", encoding="utf-8", newline="") as input_file, temporary.open("wb") as raw:
        reader = csv.DictReader(input_file)
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as compressed:
            with io.TextIOWrapper(compressed, encoding="utf-8", newline="\n") as output:
                output.write("# ECDICT complete IELTS-tagged set; MIT license; generated by Leap8\n")
                for row in reader:
                    tags = {tag.lower() for tag in clean(row.get("tag") or "").split()}
                    if "ielts" not in tags:
                        continue
                    word = clean(row.get("word") or "")
                    key = word.casefold()
                    if not word or key in seen:
                        continue
                    seen.add(key)
                    meaning = clean(row.get("translation") or row.get("definition") or "", preserve_breaks=True)
                    if not meaning:
                        meaning = "（释义待补充）"
                    identifier = "ec_" + hashlib.sha1(key.encode("utf-8")).hexdigest()[:12]
                    frequency = clean(row.get("frq") or row.get("bnc") or "")
                    fields = (
                        identifier,
                        word,
                        clean(row.get("phonetic") or ""),
                        clean(row.get("pos") or ""),
                        meaning,
                        level_for(row),
                        "IELTS",
                        frequency,
                    )
                    if any("\t" in field or "\n" in field or "\r" in field for field in fields):
                        raise ValueError(f"unescaped field in {word!r}")
                    output.write("\t".join(fields) + "\n")
                    count += 1

    if count != EXPECTED_TAGGED_WORDS:
        temporary.unlink(missing_ok=True)
        raise ValueError(f"expected {EXPECTED_TAGGED_WORDS} unique IELTS-tagged words, generated {count}")
    os.replace(temporary, destination)
    print(f"generated {count} unique IELTS-tagged words -> {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
